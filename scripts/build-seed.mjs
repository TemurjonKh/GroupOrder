// npm run menus:seed: turns supabase/menus/*.json into supabase/seed.sql.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const text = (value) => (value === null || value === undefined ? "null::text" : `'${String(value).replaceAll("'", "''")}'`);
const int = (value) => (value === null || value === undefined ? "null::integer" : `${Number(value)}::integer`);

const files = readdirSync("supabase/menus").filter((f) => f.endsWith(".json")).sort();
const statements = files.map((file) => {
  const r = JSON.parse(readFileSync(`supabase/menus/${file}`, "utf8"));
  const rows = r.dishes.map((d, i) =>
    `  (${text(d.name)}, ${text(d.category)}, ${text(d.description)}, ${text(d.photo)}, ${int(d.price)}, ${int(i)})`);
  return `with r as (
  insert into public.restaurants (name, cuisine, logo, logo_bg, delivery_link)
  values (${text(r.name)}, ${text(r.cuisine)}, ${text(r.logo)}, ${text(r.logo_bg)}, ${text(r.delivery_link)})
  returning id
)
insert into public.menu_items (restaurant_id, name, category, description, photo, price, sort_order)
select r.id, v.* from r, (values
${rows.join(",\n")}
) as v;`;
});

writeFileSync("supabase/seed.sql", `-- Generated by npm run menus:seed from supabase/menus/*.json. Do not edit by hand.
-- Real menus taken from each brand's public site. Photos stay on the brand's servers.
-- A null price means the brand does not publish one.

${statements.join("\n\n")}
`);
console.log(`supabase/seed.sql: ${files.length} restaurants`);
