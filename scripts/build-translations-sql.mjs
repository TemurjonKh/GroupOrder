// node scripts/build-translations-sql.mjs <migration file>: writes a migration that fills the English
// (and Korean chain) names from supabase/menus/translations/en.json into an existing database.
// A fresh database gets them from seed.sql instead, which reads the same file.
import { readFileSync, writeFileSync } from "node:fs";

const out = process.argv[2];
if (!out) throw new Error("Usage: node scripts/build-translations-sql.mjs supabase/migrations/<name>.sql");
const tr = JSON.parse(readFileSync("supabase/menus/translations/en.json", "utf8"));
const text = (v) => `'${String(v).replaceAll("'", "''")}'`;
const values = (map) => Object.entries(map).map(([ko, en]) => `  (${text(ko)}, ${text(en)})`).join(",\n");

writeFileSync(out, `-- English names for dishes, menu sections and restaurants, and Korean names for the chains,
-- for the language switch. Generated by scripts/build-translations-sql.mjs from
-- supabase/menus/translations/en.json. A missing translation shows the original name.

alter table public.menu_items add column if not exists name_en text;
alter table public.menu_items add column if not exists category_en text;
alter table public.restaurants add column if not exists name_en text;
alter table public.restaurants add column if not exists name_ko text;

update public.menu_items m set name_en = v.en from (values
${values(tr.dishes)}
) as v(ko, en) where m.name = v.ko;

update public.menu_items m set category_en = v.en from (values
${values(tr.categories)}
) as v(ko, en) where m.category = v.ko;

update public.restaurants r set name_en = v.en from (values
${values(tr.restaurants)}
) as v(ko, en) where r.name = v.ko;

update public.restaurants r set name_ko = v.ko from (values
${values(tr.restaurants_ko)}
) as v(en, ko) where r.name = v.en;
`);
console.log(`${out}: ${Object.keys(tr.dishes).length} dishes, ${Object.keys(tr.categories).length} sections, ${Object.keys(tr.restaurants).length + Object.keys(tr.restaurants_ko).length} restaurants`);
